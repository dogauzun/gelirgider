// Renders THIRD_PARTY_NOTICES.md to stdout. Run by `make notices`, which
// passes: the Go standard library's LICENSE, GOMODCACHE, the go-licenses
// report (deploy/notices.tmpl: name, version, license, license file per line)
// and the `license-checker --json` output for the frontend.
import { readdirSync, readFileSync } from 'node:fs'
import { basename, join } from 'node:path'

const [goLicense, modCache, goReport, npmReport] = process.argv.slice(2)
const out = []

// A fence longer than any backtick run in the text, so no license text can
// close it early.
function block(file) {
  const text = readFileSync(file, 'utf8').trimEnd()
  const longest = Math.max(2, ...(text.match(/`+/g) ?? []).map((s) => s.length))
  const fence = '`'.repeat(longest + 1)
  out.push(`${fence}text\n${text}\n${fence}\n`)
}

const licenseFile = /^(licen[cs]e|copying|notice)/i

out.push(`# Third-party notices

gelirgider is Copyright (C) 2026 Doğa Uzun, licensed under AGPL-3.0-only (see
[LICENSE](LICENSE)). The backend binary and the frontend bundle include the
third-party software listed below, each under its own license.

Generated by \`make notices\` from \`go-licenses report\` (backend) and
\`license-checker --production\` (frontend). Do not edit by hand.

## Backend

### Go standard library

License: BSD-3-Clause
`)
block(goLicense)

for (const line of readFileSync(goReport, 'utf8').split('\n').filter(Boolean)) {
  const [name, version, license, path] = line.split('\t')
  // go-licenses keeps one license file per module and sometimes picks a
  // third-party one, so take every license file in the module's root. Its
  // name is a package path when only a subpackage is used: cut the module
  // root out of the license file's path, or build it from the name.
  const dir = path
    ? path.slice(0, path.indexOf(`@${version}`) + version.length + 1)
    : join(modCache, `${name.replace(/[A-Z]/g, (c) => '!' + c.toLowerCase())}@${version}`)
  const files = readdirSync(dir)
    .filter((f) => licenseFile.test(f))
    .sort()
  if (files.length === 0) throw new Error(`no license file for ${name} in ${dir}`)
  const identified =
    license === 'Unknown'
      ? 'not identified by go-licenses'
      : `${license} (identified by go-licenses from ${basename(path)})`
  out.push(`### ${name} ${version}\n\nLicense: ${identified}\n`)
  for (const f of files) {
    out.push(`${f}:\n`)
    block(join(dir, f))
  }
}

out.push('## Frontend\n')
for (const [name, p] of Object.entries(JSON.parse(readFileSync(npmReport, 'utf8')))) {
  out.push(`### ${name}\n\nLicense: ${p.licenses}\n`)
  // license-checker falls back to the README when a package has no license file.
  if (p.licenseFile && licenseFile.test(basename(p.licenseFile))) block(p.licenseFile)
  else out.push('The package ships no license file.\n')
}

process.stdout.write(out.join('\n'))
